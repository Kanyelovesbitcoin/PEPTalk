function withRelatedFallbacks(entries: Compound[]) {
  const validIds = new Set(entries.map((compound) => compound.id));

  return entries.map((compound) => {
    const explicitRelated = (compound.relatedCompoundIds ?? []).filter((id) => id !== compound.id && validIds.has(id));

    if (explicitRelated.length > 0) {
      return {
        ...compound,
        relatedCompoundIds: explicitRelated.slice(0, 4),
      };
    }

    const primaryGoal = compound.goals[0];
    const relatedCompoundIds = entries
      .filter((candidate) => candidate.id !== compound.id && candidate.goals.includes(primaryGoal))
      .slice(0, 4)
      .map((candidate) => candidate.id);

    return {
      ...compound,
      relatedCompoundIds,
    };
  });
}

export const compounds: Compound[] = withRelatedFallbacks(compoundEntries);

export const compoundById = compounds.reduce<Record<string, Compound>>((lookup, compound) => {
  lookup[compound.id] = compound;
  return lookup;
}, {});
