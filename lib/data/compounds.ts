function defaultClass(seed: CompoundSeed) {
  if (seed.legalStatus === 'cosmetic') return 'Topical peptide reference';
  if (seed.legalStatus === 'approved-rx') return 'Prescription peptide reference';
  if (seed.legalStatus === 'investigational') return 'Investigational peptide reference';
  if (seed.regulatoryStatus === 'compounding-concern') return 'High-caution research peptide';
  return seed.nickname;
}

function defaultOrigin(seed: CompoundSeed) {
  if (seed.legalStatus === 'approved-rx') return 'Clinician-managed prescription context';
  if (seed.legalStatus === 'cosmetic') return 'Topical formulation context';
  if (seed.legalStatus === 'investigational') return 'Clinical-trial and translational research context';
  return 'Synthetic research reference';
}

function defaultEvidenceLabel(seed: CompoundSeed): NonNullable<Compound['evidenceLabel']> {
  if (seed.legalStatus === 'cosmetic') return 'Cosmetic';
  if (seed.researchStatus === 'early-research') return 'Early';
  if (seed.researchStatus === 'well-studied') return seed.legalStatus === 'approved-rx' ? 'Promising' : 'Mixed';
  return seed.legalStatus === 'investigational' ? 'Mixed' : 'Promising';
}

function defaultBreadth(seed: CompoundSeed): 1 | 2 | 3 {
  if (seed.legalStatus === 'approved-rx' || seed.researchStatus === 'well-studied') return 3;
  if (seed.researchStatus === 'promising') return 2;
  return 1;
}

function defaultEvidence(seed: CompoundSeed): EvidenceProfile {
  if (seed.legalStatus === 'approved-rx') {
    return { anecdotal: 0.28, cosmetic: 0.08, humanTrials: 0.9, preclinical: 0.78 };
  }

  if (seed.legalStatus === 'cosmetic') {
    return { anecdotal: 0.36, cosmetic: 0.82, humanTrials: 0.48, preclinical: 0.54 };
  }

  if (seed.legalStatus === 'investigational') {
    return { anecdotal: 0.32, cosmetic: 0.06, humanTrials: 0.5, preclinical: 0.68 };
  }

  return DEFAULT_EVIDENCE[seed.researchStatus];
}

function defaultPullQuote(seed: CompoundSeed) {
  return seed.evidenceNote || seed.notes[0] || seed.summary;
}

function entry(seed: CompoundSeed): Compound {
  const editorial = EDITORIAL_PROFILES[seed.id] ?? {};

  return {
    ...seed,
    ...editorial,
    breadth: editorial.breadth ?? seed.breadth ?? defaultBreadth(seed),
    class: editorial.class ?? seed.class ?? defaultClass(seed),
    evidence: editorial.evidence ?? seed.evidence ?? defaultEvidence(seed),
    evidenceLabel: editorial.evidenceLabel ?? seed.evidenceLabel ?? defaultEvidenceLabel(seed),
    origin: editorial.origin ?? seed.origin ?? defaultOrigin(seed),
    pullQuote: editorial.pullQuote ?? seed.pullQuote ?? defaultPullQuote(seed),
    tags: editorial.tags ?? seed.tags ?? getDefaultCompoundTags(seed),
    type: 'peptide',
    whatIsIt:
      `${seed.name} is included as an educational peptide reference for private tracking and research literacy. This entry is not product guidance, dosing guidance, or a use recommendation.`,
    whatIsItGoodFor: seed.context,
    howDoesItWork: seed.mechanism,
    thingsToKnow: [
      ...seed.notes,
      DEFAULT_TRACKING_DISCLAIMER,
    ],
    trackingDisclaimer: DEFAULT_TRACKING_DISCLAIMER,
  };
}

